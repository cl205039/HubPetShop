const PREENCHIDO = {
  paw: '<circle cx="12" cy="15.5" r="4.5"/><circle cx="4.7" cy="9.6" r="2.3"/><circle cx="19.3" cy="9.6" r="2.3"/><circle cx="8.6" cy="4.6" r="2.1"/><circle cx="15.4" cy="4.6" r="2.1"/>',
  star: '<polygon points="12 2 15.09 8.26 22 9.27 17 14.14 18.18 21.02 12 17.77 5.82 21.02 7 14.14 2 9.27 8.91 8.26 12 2"/>',
};

export function montarIcone(nome, tamanho = 20) {
  if (PREENCHIDO[nome]) {
    return `<svg class="icone-svg" width="${tamanho}" height="${tamanho}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">${PREENCHIDO[nome]}</svg>`;
  }
  return `<svg class="icone-svg" width="${tamanho}" height="${tamanho}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${LINHA[nome] ?? ''}</svg>`;
}

// Preenche automaticamente todo elemento estático marcado com
// data-icone="nome" (e opcionalmente data-tamanho="18") já presente no
// HTML da página. Conteúdo montado depois via JS (listas carregadas da
// API) deve chamar montarIcone() diretamente no template.
document.querySelectorAll('[data-icone]').forEach((el) => {
  const tamanho = el.dataset.tamanho ? parseInt(el.dataset.tamanho, 10) : 20;
  el.innerHTML = montarIcone(el.dataset.icone, tamanho);
});
